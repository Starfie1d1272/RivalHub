import { randomUUID } from "node:crypto";
import { eq } from "drizzle-orm";
import { Pool } from "pg";
import { expect, it, vi } from "vitest";
import { db } from "@/db/client";
import * as schema from "@/db/schema";
import { AppError, ErrorCode } from "@/lib/errors";
import { requireSeasonAdmin } from "@/lib/auth/session";
import { readAdminCommunityAward, readAdminCommunityAwardOptions } from "@/lib/admin/community-awards-read";
import { getAdminCommunityAwardDetail } from "@/lib/community-awards/data";
import { seedFixture } from "./harness/mizar";
vi.mock("next/cache", () => ({ cacheTag: vi.fn(), cacheLife: vi.fn() }));
vi.mock("@/lib/auth/session", () => ({ requireSeasonAdmin: vi.fn().mockResolvedValue({ userId: "fixture admin" }) }));
it("freshly authorizes each scoped detail/options read and refuses another season or a disabled feature", async () => {
  const fixture = await seedFixture(), other = await seedFixture();
  await db.update(schema.seasons).set({ hasCommunityAwards: true }).where(eq(schema.seasons.id, fixture.seasonId));
  await db.update(schema.seasons).set({ hasCommunityAwards: true }).where(eq(schema.seasons.id, other.seasonId));
  const [entry] = await db.select({ userId: schema.competitionEntries.representativeUserId }).from(schema.competitionEntries).where(eq(schema.competitionEntries.id, fixture.entryAId));
  const [award] = await db.insert(schema.communityAwards).values({ seasonId: fixture.seasonId, submittedByUserId: entry!.userId, name: "Scoped award", condition: "complete condition", prize: "fixture", settlementPolicy: "event_verified" }).returning();
  const input = { seasonId: fixture.seasonId, awardId: award!.id };
  const actual = await readAdminCommunityAward(input);
  expect(actual).toEqual(await getAdminCommunityAwardDetail(db, { ...input, stagePlan: [] }));
  expect(actual.condition).toBe("complete condition");
  expect(requireSeasonAdmin).toHaveBeenCalledWith(fixture.seasonId);
  const options = await readAdminCommunityAwardOptions(fixture.seasonId);
  expect(options.candidates.length).toBeGreaterThan(0); expect(options.matches.some(match => match.id === fixture.matchId)).toBe(true);
  await expect(readAdminCommunityAward({ ...input, seasonId: other.seasonId })).rejects.toMatchObject({ code: ErrorCode.NOT_FOUND });
  await expect(readAdminCommunityAward({ ...input, awardId: randomUUID() })).rejects.toMatchObject({ code: ErrorCode.NOT_FOUND });
  const pool = (db as typeof db & { $client: Pool }).$client;
  const observer = vi.spyOn(pool, "query");
  vi.mocked(requireSeasonAdmin).mockRejectedValueOnce(new AppError(ErrorCode.FORBIDDEN, "withdrawn"));
  await expect(readAdminCommunityAward(input)).rejects.toMatchObject({ code: ErrorCode.FORBIDDEN }); expect(observer).not.toHaveBeenCalled();
  vi.mocked(requireSeasonAdmin).mockRejectedValueOnce(new AppError(ErrorCode.FORBIDDEN, "withdrawn"));
  await expect(readAdminCommunityAwardOptions(fixture.seasonId)).rejects.toMatchObject({ code: ErrorCode.FORBIDDEN }); expect(observer).not.toHaveBeenCalled(); observer.mockRestore();
  await db.update(schema.seasons).set({ hasCommunityAwards: false }).where(eq(schema.seasons.id, fixture.seasonId));
  await expect(readAdminCommunityAward(input)).rejects.toMatchObject({ code: ErrorCode.NOT_FOUND });
  await expect(readAdminCommunityAwardOptions(fixture.seasonId)).rejects.toMatchObject({ code: ErrorCode.NOT_FOUND });
});
