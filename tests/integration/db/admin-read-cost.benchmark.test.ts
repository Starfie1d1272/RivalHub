import { randomUUID } from "node:crypto";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { Pool } from "pg";
import { expect, it, vi } from "vitest";
import { createLocalPool } from "./harness/database";
import { loadSeasonWorkspaceOverview } from "@/lib/admin/season-workspace/overview";
import { getPlatformOperationsOverview } from "@/lib/admin/platform-operations/overview";
import { getAdminInviteHistory, normalizeAdminInviteQuery } from "@/lib/admin/invites";

vi.mock("next/cache", () => ({ cacheTag: vi.fn(), cacheLife: vi.fn() }));

// Explicit paired experiment against exact baseline modules generated by git show.
// It is opt-in so CI correctness runs do not depend on repository history/files.
it.skipIf(process.env.RIVALHUB_ADMIN_READ_BENCHMARK !== "1")("records paired read cost on the same isolated PostgreSQL fixture", async () => {
  const pool = createLocalPool();
  const baselineOverviewPath = resolve("src/lib/admin/platform-operations/overview-baseline.ts");
  const baselineInvitesPath = resolve("src/lib/admin/invites-baseline.ts");
  const beforeOverview = await import(/* @vite-ignore */ baselineOverviewPath) as { getPlatformOperationsOverview: typeof getPlatformOperationsOverview };
  const beforeInvites = await import(/* @vite-ignore */ baselineInvitesPath) as { getAdminInviteHistory: typeof getAdminInviteHistory };
  const baselineMajorPath = resolve("src/lib/admin/season-workspace/overview-baseline.ts");
  const beforeMajor = await import(/* @vite-ignore */ baselineMajorPath) as { loadSeasonWorkspaceOverview: typeof loadSeasonWorkspaceOverview };
  const season = randomUUID();
  const now = new Date();
  const people = Array.from({ length: 1000 }, () => randomUUID());
  const invites = Array.from({ length: 1000 }, () => randomUUID());
  const runs: { reader: string; version: string; round: number; elapsedMs: number; queries: number; returnedRows: number; returnedJsonBytes: number }[] = [];
  const original = Pool.prototype.query;
  let measurements = { queries: 0, returnedRows: 0, returnedJsonBytes: 0 };
  const spy = vi.spyOn(Pool.prototype, "query").mockImplementation((function(this: Pool, ...args: unknown[]) {
    const result = Reflect.apply(original, this, args);
    if (!result || typeof result.then !== "function") return result;
    return result.then((value: { rows: unknown[] }) => {
      measurements.queries++;
      measurements.returnedRows += value.rows.length;
      measurements.returnedJsonBytes += Buffer.byteLength(JSON.stringify(value.rows));
      return value;
    });
  }) as typeof original);
  try {
    await pool.query("insert into users (id,email,created_at) select id,id::text || '@benchmark.test',$2::timestamptz from unnest($1::uuid[]) id", [people, new Date(now.getTime() - 86400000)]);
    await pool.query("insert into admin_invites (id,code,created_by,role,created_at) select id,id::text,'benchmark','super_admin',$2::timestamptz from unnest($1::uuid[]) id", [invites, now]);
    await pool.query("insert into seasons (id,slug,name,kind,competition_template,status) values ($1::uuid,$1::text,'benchmark','major','major','playing')", [season]);
    const query = normalizeAdminInviteQuery({ role: "super_admin" });
    const readers = [
      { name: "operations", before: () => beforeOverview.getPlatformOperationsOverview(now), after: () => getPlatformOperationsOverview(now) },
      { name: "major-summary", before: async () => { const data = await beforeMajor.loadSeasonWorkspaceOverview(season); return data && { summary: data.summary, nextAction: data.nextAction }; }, after: async () => { const data = await loadSeasonWorkspaceOverview(season); return data && { summary: data.summary, nextAction: data.nextAction }; } },
      { name: "invites", before: () => beforeInvites.getAdminInviteHistory(query), after: () => getAdminInviteHistory(query, now) },
    ];
    for (const reader of readers) {
      expect(await reader.after()).toEqual(await reader.before());
      for (let round = 0; round < 10; round++) {
        for (const version of (round % 2 ? ["after", "before"] : ["before", "after"]) as ("before" | "after")[]) {
          measurements = { queries: 0, returnedRows: 0, returnedJsonBytes: 0 };
          const started = performance.now();
          await reader[version]();
          runs.push({ reader: reader.name, version, round, elapsedMs: performance.now() - started, ...measurements });
        }
      }
    }
    const report = { baseline: "4ebecf5d5e1b629371c7d0c8851b6bab9c31d7f8", environment: "isolated loopback PostgreSQL; no simulated RTT; warm paired alternating runs", fixture: { additionalUsers: people.length, additionalInvites: invites.length, majorEntrants: 0 }, exclusions: ["browser LCP/CLS", "pool waiting under mixed load", "production improvement"], runs };
    if (process.env.RIVALHUB_ADMIN_BENCHMARK_OUTPUT) writeFileSync(process.env.RIVALHUB_ADMIN_BENCHMARK_OUTPUT, JSON.stringify(report, null, 2) + "\n");
    console.log(JSON.stringify(report));
  } finally {
    spy.mockRestore();
    await pool.query("delete from admin_invites where id=any($1::uuid[])", [invites]);
    await pool.query("delete from seasons where id=$1", [season]);
    await pool.query("delete from users where id=any($1::uuid[])", [people]);
    await pool.end();
  }
});
